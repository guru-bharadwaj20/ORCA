import type { InferredEnv } from '../ai/schema.js';
import type { ServicePlan } from '../plan/types.js';

export function selectEnvVars(
  inferred: InferredEnv,
  plan: Pick<ServicePlan, 'services'>
): InferredEnv['variables'] {
  const covered = new Set<string>();
  for (const node of plan.services) {
    for (const key of Object.keys(node.environment)) covered.add(key);
  }
  return inferred.variables.filter(
    (variable) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(variable.key) && !covered.has(variable.key)
  );
}

export function buildEnvFile(inferred: InferredEnv, plan: ServicePlan): string {
  const variables = selectEnvVars(inferred, plan);
  if (variables.length === 0) return '';

  const lines = [
    '# Generated by ORCA — local development defaults inferred from the repo.',
    '# Database wiring is injected by docker-compose directly and is not duplicated here.',
    '# Review the placeholder secrets before sharing this stack.',
  ];
  for (const variable of variables) {
    lines.push('', `# ${variable.required ? '(required) ' : ''}${variable.reason}`);
    // Compose's dotenv parser processes escape sequences inside double-quoted values, so a
    // backslash must be escaped first (before the quote), or a Windows path / regex value
    // would be corrupted. Order matters: backslashes, then quotes.
    const value = /[\s#'"]/.test(variable.value)
      ? `"${variable.value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
      : variable.value;
    lines.push(`${variable.key}=${value}`);
  }
  return `${lines.join('\n')}\n`;
}
